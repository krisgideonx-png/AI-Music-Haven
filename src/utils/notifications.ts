export interface BuildNotificationsInput {
  takedowns: TrackTakedownNotice[];
  reports: CopyrightReport[];
  tracks: AudioTrack[];
  activityNotifications?: HavenNotification[];
  userUid?: string | null;
  isAdmin?: boolean;
  readIds?: ReadonlySet<string>;
  dismissedIds?: ReadonlySet<string>;
}

export function buildNotificationsFeed({
  takedowns,
  reports,
  tracks,
  activityNotifications = [],
  userUid = null,
  isAdmin = false,
  readIds = new Set<string>(),
  dismissedIds = new Set<string>(),
}: BuildNotificationsInput): HavenNotification[] {
  const trackById = new Map<string, AudioTrack>();
  for (const t of tracks) {
    trackById.set(t.id, t);
  }

  const items: HavenNotification[] = [];

  // 1. Takedown notices relevant to the current user (creator notices or admin moderation log)
  takedowns
    .filter((td) => (isAdmin ? true : Boolean(userUid && td.targetUploaderUid === userUid)))
    .forEach((td, idx) => {
      const id = `td-${td.id}`;
      if (dismissedIds.has(id)) return;
      items.push({
        id,
        type: 'takedown',
        title: `Takedown Notice: ${td.trackTitle}`,
        message: td.reason,
        time: td.createdAt || 'Recently',
        createdAtMs: 900_000_000_000 - idx,
        read: readIds.has(id),
        trackId: td.trackId,
        trackTitle: td.trackTitle,
        takedownId: td.id,
        actorName: td.creatorName,
        metadata: {
          reason: td.reason,
          autoGenerated: td.autoGenerated,
          adminEmail: td.adminEmail,
        },
      });
    });

  // 2. Admin moderation & copyright reports
  if (isAdmin) {
    reports.forEach((rep, idx) => {
      const id = `rep-${rep.id}`;
      if (dismissedIds.has(id)) return;
      const linkedTrack = trackById.get(rep.trackId);
      const isClosed = rep.status === 'Resolved' || rep.status === 'Dismissed';
      items.push({
        id,
        type: 'moderation_report',
        title: `Moderation Report (${rep.status}): ${rep.trackTitle}`,
        message: `${rep.claimant} reported "${rep.trackTitle}" by ${rep.creatorName}: ${rep.reason}`,
        time: rep.createdAt || 'Recently',
        createdAtMs: 800_000_000_000 - idx,
        read: isClosed || readIds.has(id),
        trackId: rep.trackId,
        trackTitle: linkedTrack?.title || rep.trackTitle,
        reportId: rep.id,
        actorName: rep.claimant,
        metadata: {
          reason: rep.reason,
          claimant: rep.claimant,
          reportStatus: rep.status,
          riskScore: rep.riskScore,
          genre: linkedTrack?.genre,
        },
      });
    });
  }

  // 3. Dynamic activity notifications (e.g., published tracks during session)
  activityNotifications.forEach((notif) => {
    if (dismissedIds.has(notif.id)) return;
    items.push({
      ...notif,
      read: notif.read || readIds.has(notif.id),
    });
  });

  // 4. Community & catalog notifications anchored to real catalog tracks
  const obsidian = trackById.get('trk-01-obsidian');
  if (obsidian && !dismissedIds.has('n-1')) {
    items.push({
      id: 'n-1',
      type: 'track_liked',
      title: `New Track Liked: ${obsidian.title}`,
      message: `Elena Rostova liked "${obsidian.title}" and added it to her Late Night Cyber Drift rotation.`,
      time: '10m ago',
      createdAtMs: 500_000_000_003,
      read: readIds.has('n-1'),
      trackId: obsidian.id,
      trackTitle: obsidian.title,
      actorName: 'Elena Rostova',
      metadata: {
        genre: obsidian.genre,
        subgenre: obsidian.subgenre,
        plays: obsidian.plays,
        downloads: obsidian.downloads,
      },
    });
  }

  const biolum = trackById.get('trk-04-bioluminescent');
  if (biolum && !dismissedIds.has('n-2')) {
    items.push({
      id: 'n-2',
      type: 'track_milestone',
      title: `Download Milestone: ${biolum.title}`,
      message: `"${biolum.title}" reached ${biolum.downloads.toLocaleString()} community downloads across AI Music Haven creators.`,
      time: '1h ago',
      createdAtMs: 500_000_000_002,
      read: readIds.has('n-2'),
      trackId: biolum.id,
      trackTitle: biolum.title,
      actorName: biolum.creator,
      metadata: {
        genre: biolum.genre,
        subgenre: biolum.subgenre,
        plays: biolum.plays,
        downloads: biolum.downloads,
      },
    });
  }

  const lagos = trackById.get('trk-02-lagos');
  if (lagos && !dismissedIds.has('n-3')) {
    items.push({
      id: 'n-3',
      type: 'category_verified',
      title: `Category Verified: ${lagos.title}`,
      message: `All 8 metadata attributes (Genre, Subgenre, Mood, BPM, Key, Instruments, Energy, and License) are confirmed for "${lagos.title}".`,
      time: '3h ago',
      createdAtMs: 500_000_000_001,
      read: readIds.has('n-3'),
      trackId: lagos.id,
      trackTitle: lagos.title,
      actorName: lagos.creator,
      metadata: {
        genre: lagos.genre,
        subgenre: lagos.subgenre,
        plays: lagos.plays,
        downloads: lagos.downloads,
      },
    });
  }

  return items.sort((a, b) => b.createdAtMs - a.createdAtMs);
}

export function filterNotifications(
  notifications: HavenNotification[],
  filter: NotificationFilter
): HavenNotification[] {
  if (filter === 'all') return notifications;
  if (filter === 'unread') return notifications.filter((n) => !n.read);
  if (filter === 'moderation') {
    return notifications.filter((n) => getNotificationTypeMeta(n.type).category === 'moderation');
  }
  return notifications.filter((n) => getNotificationTypeMeta(n.type).category === 'tracks');
}

export function countUnreadNotifications(notifications: HavenNotification[]): number {
  return notifications.filter((n) => !n.read).length;
}

const STORAGE_PREFIX = 'haven_notification_prefs_v1_';

export interface NotificationPrefs {
  readIds: string[];
  dismissedIds: string[];
}

export function loadNotificationPrefs(scopeKey: string): NotificationPrefs {
  if (typeof window === 'undefined') {
    return { readIds: [], dismissedIds: [] };
  }
  try {
    const raw = window.localStorage.getItem(`${STORAGE_PREFIX}${scopeKey}`);
    if (!raw) return { readIds: [], dismissedIds: [] };
    const parsed = JSON.parse(raw);
    return {
      readIds: Array.isArray(parsed?.readIds) ? parsed.readIds.filter((x: unknown) => typeof x === 'string') : [],
      dismissedIds: Array.isArray(parsed?.dismissedIds)
        ? parsed.dismissedIds.filter((x: unknown) => typeof x === 'string')
        : [],
    };
  } catch {
    return { readIds: [], dismissedIds: [] };
  }
}

export function saveNotificationPrefs(
  scopeKey: string,
  readIds: ReadonlySet<string>,
  dismissedIds: ReadonlySet<string>
): void {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.setItem(
      `${STORAGE_PREFIX}${scopeKey}`,
      JSON.stringify({
        readIds: Array.from(readIds),
        dismissedIds: Array.from(dismissedIds),
      })
    );
  } catch {
    // Ignore storage quota / privacy restrictions
  }
}
