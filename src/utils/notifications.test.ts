test('buildNotificationsFeed generates typed notifications for creators and admins', () => {
  const tracks: AudioTrack[] = [
    makeTrack({ id: 'trk-01-obsidian', title: 'Obsidian Resonance' }),
    makeTrack({ id: 'trk-04-bioluminescent', title: 'Bioluminescent Dawn', downloads: 1050 }),
    makeTrack({ id: 'trk-02-lagos', title: 'Lagos Neon Mirage' }),
  ];

  const takedowns: TrackTakedownNotice[] = [
    {
      id: 'td-1',
      trackId: 'trk-u1',
      trackTitle: 'Creator Song',
      creatorName: 'Artist A',
      targetUploaderUid: 'uid-a',
      reason: 'Metadata mismatch detected during review.',
      autoGenerated: false,
      adminEmail: 'xtianboy5@gmail.com',
      createdAt: 'Just now',
    },
    {
      id: 'td-2',
      trackId: 'trk-u2',
      trackTitle: 'Other Creator Song',
      creatorName: 'Artist B',
      targetUploaderUid: 'uid-b',
      reason: 'Licensing verification needed.',
      autoGenerated: true,
      adminEmail: 'xtianboy5@gmail.com',
      createdAt: '2m ago',
    },
  ];

  const reports: CopyrightReport[] = [
    {
      id: 'rep-01',
      trackId: 'trk-01-obsidian',
      trackTitle: 'Obsidian Resonance',
      creatorName: 'Kaelen Voss',
      claimant: 'Rights Guild',
      reason: 'Sample clearance inquiry',
      status: 'Pending Review',
      riskScore: 42,
      createdAt: '1h ago',
    },
  ];

  // Creator A only sees their own takedown + track notifications (no admin reports, no Artist B takedown)
  const creatorFeed = buildNotificationsFeed({
    takedowns,
    reports,
    tracks,
    userUid: 'uid-a',
    isAdmin: false,
  });

  assert.equal(creatorFeed.some((n) => n.id === 'td-td-1' && n.type === 'takedown'), true);
  assert.equal(creatorFeed.some((n) => n.id === 'td-td-2'), false);
  assert.equal(creatorFeed.some((n) => n.type === 'moderation_report'), false);
  assert.equal(countUnreadNotifications(creatorFeed), 4);

  // Admin sees all takedowns + moderation reports + track notifications
  const adminFeed = buildNotificationsFeed({
    takedowns,
    reports,
    tracks,
    userUid: 'admin-uid',
    isAdmin: true,
    readIds: new Set(['n-1']),
    dismissedIds: new Set(['n-3']),
  });

  assert.equal(adminFeed.some((n) => n.id === 'td-td-2'), true);
  assert.equal(adminFeed.some((n) => n.id === 'rep-rep-01' && n.type === 'moderation_report'), true);
  assert.equal(adminFeed.some((n) => n.id === 'n-3'), false);
  assert.equal(adminFeed.find((n) => n.id === 'n-1')?.read, true);
});

test('filterNotifications and getNotificationTypeMeta classify moderation vs track activity', () => {
  const tracks = [makeTrack({ id: 'trk-01-obsidian' }), makeTrack({ id: 'trk-04-bioluminescent' })];
  const reports: CopyrightReport[] = [
    {
      id: 'rep-01',
      trackId: 'trk-01-obsidian',
      trackTitle: 'Obsidian Resonance',
      creatorName: 'Kaelen Voss',
      claimant: 'Rights Guild',
      reason: 'Sample clearance inquiry',
      status: 'Resolved',
      riskScore: 15,
      createdAt: '1h ago',
    },
  ];

  const feed = buildNotificationsFeed({
    takedowns: [],
    reports,
    tracks,
    isAdmin: true,
    readIds: new Set(['n-1']),
  });

  assert.equal(filterNotifications(feed, 'moderation').length, 1);
  assert.equal(filterNotifications(feed, 'tracks').length, 2);
  assert.equal(filterNotifications(feed, 'unread').length, 1); // only n-2 is unread (rep-01 is Resolved, n-1 is read)
  assert.equal(getNotificationTypeMeta('takedown').category, 'moderation');
  assert.equal(getNotificationTypeMeta('track_published').category, 'tracks');
});
