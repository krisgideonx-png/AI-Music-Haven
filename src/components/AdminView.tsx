import React, { useState, useMemo } from 'react';
import {
  ShieldAlert,
  AlertTriangle,
  Trash2,
  Eye,
  Search,
  Sparkles,
  Edit3,
  Music2,
  Headphones,
  UploadCloud,
  CheckCircle2,
  Star,
  X,
} from 'lucide-react';
import type { CopyrightReport, AudioTrack, TrackTakedownNotice } from '../types/index.ts';
import { ADMIN_EMAIL } from '../utils/accessControl.ts';

interface AdminViewProps {
  adminEmail?: string | null;
  reports: CopyrightReport[];
  tracks: AudioTrack[];
  takedowns?: TrackTakedownNotice[];
  onOpenTrackDetails: (track: AudioTrack) => void;
  onEditTrackDetails: (track: AudioTrack) => void;
  onTakeDownTrack?: (
    track: AudioTrack,
    reason: string,
    autoGenerated: boolean
  ) => Promise<void> | void;
  onResolveReport: (reportId: string, action: 'Dismissed' | 'Resolved') => void;
  onSetFeaturedTrack?: (trackId: string) => void;
}

export const AdminView: React.FC<AdminViewProps> = ({
  adminEmail = ADMIN_EMAIL,
  reports,
  tracks,
  takedowns = [],
  onOpenTrackDetails,
  onEditTrackDetails,
  onTakeDownTrack,
  onResolveReport,
  onSetFeaturedTrack,
}) => {
  const [activeTab, setActiveTab] = useState<'songs' | 'disputes'>('songs');
  const [songQuery, setSongQuery] = useState('');
  const [songFilter, setSongFilter] = useState<'all' | 'uploads' | 'catalog' | 'unconfirmed'>('all');
  const [filterStatus, setFilterStatus] = useState<string>('All');
  const [takedownTarget, setTakedownTarget] = useState<AudioTrack | null>(null);
  const [takedownReason, setTakedownReason] = useState('');
  const [isTakingDown, setIsTakingDown] = useState(false);
  const [actionNotice, setActionNotice] = useState<string | null>(null);

  const userUploadCount = useMemo(
    () => tracks.filter((t) => Boolean(t.uploaderUid)).length,
    [tracks]
  );

  const totalStreams = useMemo(
    () => tracks.reduce((sum, t) => sum + (t.plays || 0), 0),
    [tracks]
  );

  const pendingReportsCount = useMemo(
    () => reports.filter((r) => r.status === 'Pending Review' || r.status === 'Investigating').length,
    [reports]
  );

  const filteredTracks = useMemo(() => {
    const q = songQuery.trim().toLowerCase();
    return tracks.filter((t) => {
      if (songFilter === 'uploads' && !t.uploaderUid) return false;
      if (songFilter === 'catalog' && Boolean(t.uploaderUid)) return false;
      if (songFilter === 'unconfirmed' && t.categoryConfirmed !== false) return false;

      if (!q) return true;
      return (
        t.title.toLowerCase().includes(q) ||
        t.creator.toLowerCase().includes(q) ||
        t.creatorHandle.toLowerCase().includes(q) ||
        t.genre.toLowerCase().includes(q) ||
        t.subgenre.toLowerCase().includes(q) ||
        t.aiToolOrigin.toLowerCase().includes(q)
      );
    });
  }, [tracks, songQuery, songFilter]);

  const filteredReports = reports.filter((r) =>
    filterStatus === 'All' ? true : r.status === filterStatus
  );

  const handleOpenTakedownModal = (track: AudioTrack) => {
    setTakedownTarget(track);
    setTakedownReason('');
  };

  const handleConfirmTakedown = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!onTakeDownTrack || !takedownTarget) return;

    setIsTakingDown(true);
    try {
      let finalReason = takedownReason.trim();
      let autoGenerated = false;

      if (!finalReason) {
        autoGenerated = true;
        try {
          const response = await fetch('/api/generate-takedown-reason', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
              title: takedownTarget.title,
              creator: takedownTarget.creator,
              genre: takedownTarget.genre,
              license: takedownTarget.license,
            }),
          });
          const data = await response.json();
          if (typeof data?.reason === 'string' && data.reason.trim()) {
            finalReason = data.reason.trim();
          }
        } catch {
          // Graceful deterministic fallback below
        }
        if (!finalReason) {
          finalReason = `Your song "${takedownTarget.title}" was taken down during an AI Music Haven administrative moderation review due to metadata verification, licensing compliance, or archive quality standards.`;
        }
      }

      await onTakeDownTrack(takedownTarget, finalReason, autoGenerated);
      setActionNotice(
        `Taken down "${takedownTarget.title}". ${
          autoGenerated ? 'Auto-generated takedown reason' : 'Admin takedown reason'
        } delivered to ${takedownTarget.creator}.`
      );
      setTakedownTarget(null);
      setTakedownReason('');
      setTimeout(() => setActionNotice(null), 5000);
    } finally {
      setIsTakingDown(false);
    }
  };

  return (
    <div className="space-y-8 pb-24">
      {/* Header */}
      <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-4">
        <div>
          <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-[#EF4444]/15 border border-[#EF4444]/30 text-xs font-mono-tech text-[#EF4444] mb-1.5">
            <ShieldAlert className="w-3.5 h-3.5" />
            <span>Admin Console · {adminEmail || ADMIN_EMAIL}</span>
          </div>
          <h1 className="font-display font-bold text-2xl sm:text-4xl text-white">
            Admin Dashboard
          </h1>
          <p className="text-xs sm:text-sm text-[#958ea0] mt-1 max-w-2xl">
            Full platform control: only your admin account can edit all songs across AI Music Haven, while creators can only edit their own uploads.
          </p>
        </div>

        {/* Tab switch */}
        <div className="flex items-center gap-1.5 p-1 rounded-xl bg-[#161622] border border-white/10 text-xs font-mono-tech self-start lg:self-auto">
          <button
            type="button"
            onClick={() => setActiveTab('songs')}
            className={`px-3.5 py-2 rounded-lg transition-colors ${
              activeTab === 'songs' ? 'bg-[#8B5CF6] text-white' : 'text-[#958ea0] hover:text-white'
            }`}
          >
            All Songs ({tracks.length})
          </button>
          <button
            type="button"
            onClick={() => setActiveTab('disputes')}
            className={`px-3.5 py-2 rounded-lg transition-colors ${
              activeTab === 'disputes' ? 'bg-[#8B5CF6] text-white' : 'text-[#958ea0] hover:text-white'
            }`}
          >
            Moderation Queue ({reports.length})
          </button>
        </div>
      </div>

      {/* Action Toast */}
      {actionNotice && (
        <div className="p-3.5 rounded-xl bg-[#10B981]/15 border border-[#10B981]/30 text-xs font-mono-tech text-[#10B981] flex items-center gap-2">
          <CheckCircle2 className="w-4 h-4 shrink-0" />
          <span>{actionNotice}</span>
        </div>
      )}

      {/* Admin KPI Summary Cards */}
      <div className="grid grid-cols-2 lg:grid-cols-4 gap-4">
        <div className="p-4 sm:p-5 rounded-2xl bg-[#161622]/80 border border-white/10 space-y-1.5">
          <div className="flex items-center justify-between text-xs text-[#958ea0] font-mono-tech">
            <span>Editable Songs</span>
            <Music2 className="w-4 h-4 text-[#06B6D4]" />
          </div>
          <span className="font-display font-bold text-2xl sm:text-3xl text-white block">
            {tracks.length}
          </span>
          <span className="text-[11px] font-mono-tech text-[#10B981] block">
            Full Admin Edit Access
          </span>
        </div>

        <div className="p-4 sm:p-5 rounded-2xl bg-[#161622]/80 border border-white/10 space-y-1.5">
          <div className="flex items-center justify-between text-xs text-[#958ea0] font-mono-tech">
            <span>Creator Uploads</span>
            <UploadCloud className="w-4 h-4 text-[#8B5CF6]" />
          </div>
          <span className="font-display font-bold text-2xl sm:text-3xl text-white block">
            {userUploadCount}
          </span>
          <span className="text-[11px] font-mono-tech text-[#958ea0] block">
            Cloud-persisted user songs
          </span>
        </div>

        <div className="p-4 sm:p-5 rounded-2xl bg-[#161622]/80 border border-white/10 space-y-1.5">
          <div className="flex items-center justify-between text-xs text-[#958ea0] font-mono-tech">
            <span>Total Streams</span>
            <Headphones className="w-4 h-4 text-[#10B981]" />
          </div>
          <span className="font-display font-bold text-2xl sm:text-3xl text-white block">
            {totalStreams.toLocaleString()}
          </span>
          <span className="text-[11px] font-mono-tech text-[#06B6D4] block truncate">
            Featured: {tracks[0]?.title || '—'}
          </span>
        </div>

        <div className="p-4 sm:p-5 rounded-2xl bg-[#161622]/80 border border-white/10 space-y-1.5">
          <div className="flex items-center justify-between text-xs text-[#958ea0] font-mono-tech">
            <span>Open Inquiries</span>
            <AlertTriangle className="w-4 h-4 text-[#F59E0B]" />
          </div>
          <span className="font-display font-bold text-2xl sm:text-3xl text-white block">
            {pendingReportsCount}
          </span>
          <span className="text-[11px] font-mono-tech text-[#958ea0] block">
            Copyright &amp; quality reviews
          </span>
        </div>
      </div>

      {/* ALL SONGS MANAGEMENT TAB */}
      {activeTab === 'songs' && (
        <div className="space-y-4">
          <div className="flex flex-col md:flex-row md:items-center justify-between gap-3">
            {/* Search Box */}
            <div className="relative flex-1 max-w-md">
              <Search className="w-4 h-4 text-[#958ea0] absolute left-3.5 top-1/2 -translate-y-1/2 pointer-events-none" />
              <input
                type="text"
                value={songQuery}
                onChange={(e) => setSongQuery(e.target.value)}
                placeholder="Search all songs by title, creator, genre, or AI origin..."
                aria-label="Search all songs in admin dashboard"
                className="w-full bg-[#161622] text-xs text-white placeholder-[#958ea0] pl-10 pr-4 py-2.5 rounded-xl border border-white/10 focus:border-[#06B6D4]/50 focus:outline-none"
              />
            </div>

            {/* Source Filters */}
            <div className="flex flex-wrap items-center gap-1.5 text-xs font-mono-tech">
              {[
                { id: 'all' as const, label: `All (${tracks.length})` },
                { id: 'uploads' as const, label: `Creator Uploads (${userUploadCount})` },
                { id: 'catalog' as const, label: `Curated Catalog (${tracks.length - userUploadCount})` },
                {
                  id: 'unconfirmed' as const,
                  label: `Needs Category Review (${tracks.filter((t) => t.categoryConfirmed === false).length})`,
                },
              ].map((f) => (
                <button
                  key={f.id}
                  type="button"
                  onClick={() => setSongFilter(f.id)}
                  className={`px-3 py-1.5 rounded-lg border transition-colors ${
                    songFilter === f.id
                      ? 'bg-[#8B5CF6]/25 text-white border-[#8B5CF6]/50'
                      : 'bg-[#161622]/70 text-[#958ea0] hover:text-white border-white/10'
                  }`}
                >
                  {f.label}
                </button>
              ))}
            </div>
          </div>

          <div className="rounded-2xl border border-white/10 overflow-hidden bg-[#161622]/60 backdrop-blur-xl">
            <div className="overflow-x-auto">
              <table className="w-full text-left text-xs font-mono-tech">
                <thead className="bg-[#08080C] text-[#958ea0] border-b border-white/5 uppercase text-[10px]">
                  <tr>
                    <th className="py-3 px-4">Song &amp; Creator</th>
                    <th className="py-3 px-4">Source</th>
                    <th className="py-3 px-4">Genre / Mood</th>
                    <th className="py-3 px-4">License</th>
                    <th className="py-3 px-4">Streams</th>
                    <th className="py-3 px-4 text-right">Admin Actions</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-white/5 text-[#cbc3d7]">
                  {filteredTracks.map((track, idx) => {
                    const isFeatured = idx === 0 && !songQuery && songFilter === 'all';

                    return (
                      <tr key={track.id} className="hover:bg-white/[0.02] transition-colors">
                        <td className="py-3 px-4">
                          <div className="flex items-center gap-3 min-w-[200px]">
                            <img
                              src={track.coverArt}
                              alt={track.title}
                              className="w-10 h-10 rounded-lg object-cover shrink-0 border border-white/10"
                            />
                            <div className="min-w-0">
                              <div className="flex items-center gap-1.5">
                                <span className="font-sans font-semibold text-white truncate max-w-[190px]">
                                  {track.title}
                                </span>
                                {isFeatured && (
                                  <span className="inline-flex items-center gap-0.5 text-[9px] px-1.5 py-0.5 rounded bg-[#F59E0B]/15 text-[#F59E0B] border border-[#F59E0B]/30 shrink-0">
                                    <Star className="w-2.5 h-2.5 fill-current" />
                                    Featured
                                  </span>
                                )}
                              </div>
                              <span className="text-[11px] text-[#958ea0] block truncate">
                                {track.creator} · {track.creatorHandle}
                              </span>
                            </div>
                          </div>
                        </td>
                        <td className="py-3 px-4">
                          {track.uploaderUid ? (
                            <span className="text-[10px] px-2 py-0.5 rounded bg-[#06B6D4]/15 text-[#06B6D4] border border-[#06B6D4]/30">
                              Creator Upload
                            </span>
                          ) : (
                            <span className="text-[10px] px-2 py-0.5 rounded bg-[#8B5CF6]/15 text-[#acedff] border border-[#8B5CF6]/30">
                              Haven Catalog
                            </span>
                          )}
                        </td>
                        <td className="py-3 px-4">
                          <span className="text-white block">{track.genre}</span>
                          <span className="text-[10px] text-[#958ea0]">
                            {track.mood} · {track.bpm} BPM
                          </span>
                        </td>
                        <td className="py-3 px-4">
                          <span className="text-[10px] px-2 py-0.5 rounded bg-[#10B981]/10 text-[#10B981] border border-[#10B981]/20 whitespace-nowrap">
                            {track.license}
                          </span>
                        </td>
                        <td className="py-3 px-4 text-white font-bold">
                          {track.plays.toLocaleString()}
                        </td>
                        <td className="py-3 px-4 text-right">
                          <div className="inline-flex items-center gap-1.5 justify-end">
                            <button
                              type="button"
                              onClick={() => onEditTrackDetails(track)}
                              aria-label={`Edit ${track.title}`}
                              className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg bg-gradient-to-r from-[#8B5CF6]/30 to-[#06B6D4]/25 hover:from-[#8B5CF6]/45 hover:to-[#06B6D4]/40 border border-[#8B5CF6]/50 text-white text-[11px] transition-all"
                            >
                              <Edit3 className="w-3 h-3 text-[#06B6D4]" />
                              <span>Edit Song</span>
                            </button>
                            {onSetFeaturedTrack && (
                              <button
                                type="button"
                                onClick={() => {
                                  onSetFeaturedTrack(track.id);
                                  setActionNotice(`Set "${track.title}" as Featured Masterwork.`);
                                  setTimeout(() => setActionNotice(null), 3500);
                                }}
                                className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg bg-white/5 hover:bg-[#F59E0B]/20 border border-white/10 hover:border-[#F59E0B]/40 text-[#e4e1e8] text-[11px] transition-colors"
                              >
                                <Sparkles className="w-3 h-3 text-[#F59E0B]" />
                                <span>Feature</span>
                              </button>
                            )}
                            <button
                              type="button"
                              onClick={() => onOpenTrackDetails(track)}
                              aria-label={`Inspect ${track.title}`}
                              className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg bg-white/5 hover:bg-white/10 text-white text-[11px]"
                            >
                              <Eye className="w-3 h-3" />
                              <span>Inspect</span>
                            </button>
                            {onTakeDownTrack && (
                              <button
                                type="button"
                                onClick={() => handleOpenTakedownModal(track)}
                                aria-label={`Take down ${track.title}`}
                                title="Take down song & notify creator"
                                className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg bg-[#EF4444]/10 hover:bg-[#EF4444]/25 text-[#EF4444] border border-[#EF4444]/25 text-[11px] transition-colors"
                              >
                                <Trash2 className="w-3 h-3" />
                                <span>Take Down</span>
                              </button>
                            )}
                          </div>
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>

            {filteredTracks.length === 0 && (
              <div className="p-8 text-center text-xs text-[#958ea0]">
                No songs match your current search or filter.
              </div>
            )}
          </div>
        </div>
      )}

      {/* DISPUTES / COPYRIGHT TAB */}
      {activeTab === 'disputes' && (
        <div className="space-y-4">
          <div className="p-4 rounded-2xl bg-[#08080C] border border-white/10 flex items-start gap-3 text-xs text-[#cbc3d7]">
            <AlertTriangle className="w-4 h-4 text-[#F59E0B] shrink-0 mt-0.5" />
            <p className="leading-relaxed">
              <strong className="text-white">Copyright-Risk Advisory:</strong> The automated risk score (0-100) is an assistance mechanism based on acoustic fingerprinting and metadata keywords. It does not constitute definitive proof of ownership or infringement. All claims require human assessment.
            </p>
          </div>

          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
            <h3 className="font-display font-semibold text-base text-white">
              Pending Disputes &amp; Inquiries
            </h3>
            <div className="flex items-center gap-1 text-xs font-mono-tech">
              <span className="text-[#958ea0]">Filter:</span>
              {['All', 'Pending Review', 'Investigating', 'Resolved'].map((st) => (
                <button
                  key={st}
                  type="button"
                  onClick={() => setFilterStatus(st)}
                  className={`px-2 py-0.5 rounded ${
                    filterStatus === st ? 'bg-white/10 text-white' : 'text-[#958ea0] hover:text-white'
                  }`}
                >
                  {st}
                </button>
              ))}
            </div>
          </div>

          <div className="space-y-3">
            {filteredReports.map((report) => (
              <div
                key={report.id}
                className="p-4 sm:p-5 rounded-2xl bg-[#161622]/80 border border-white/10 space-y-3"
              >
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
                  <div className="flex items-center gap-2.5">
                    <span className="font-display font-semibold text-sm text-white">
                      {report.trackTitle}
                    </span>
                    <span className="text-[10px] font-mono-tech text-[#958ea0]">
                      by {report.creatorName}
                    </span>
                  </div>

                  <div className="flex items-center gap-2">
                    <span className="text-[10px] font-mono-tech px-2 py-0.5 rounded bg-[#F59E0B]/10 text-[#F59E0B] border border-[#F59E0B]/20">
                      Risk Assist: {report.riskScore}/100
                    </span>
                    <span
                      className={`text-[10px] font-mono-tech px-2 py-0.5 rounded ${
                        report.status === 'Resolved'
                          ? 'bg-[#10B981]/15 text-[#10B981]'
                          : 'bg-[#EF4444]/15 text-[#EF4444]'
                      }`}
                    >
                      {report.status}
                    </span>
                  </div>
                </div>

                <div className="text-xs text-[#cbc3d7] bg-[#08080C] p-3 rounded-xl border border-white/5 space-y-1">
                  <div className="flex justify-between text-[10px] font-mono-tech text-[#958ea0]">
                    <span>Claimant: {report.claimant}</span>
                    <span>Received: {report.createdAt}</span>
                  </div>
                  <p>&quot;{report.reason}&quot;</p>
                </div>

                <div className="flex items-center justify-between pt-1">
                  <span className="text-[10px] font-mono-tech text-[#958ea0]">
                    Report ID: {report.id}
                  </span>

                  <div className="flex items-center gap-2">
                    <button
                      type="button"
                      onClick={() => onResolveReport(report.id, 'Dismissed')}
                      className="px-3 py-1 rounded-lg bg-white/5 hover:bg-white/10 text-white text-xs font-mono-tech"
                    >
                      Dismiss Claim
                    </button>
                    <button
                      type="button"
                      onClick={() => onResolveReport(report.id, 'Resolved')}
                      className="px-3 py-1 rounded-lg bg-[#10B981]/20 hover:bg-[#10B981]/30 text-[#10B981] text-xs font-mono-tech border border-[#10B981]/30"
                    >
                      Mark Resolved
                    </button>
                  </div>
                </div>
              </div>
            ))}
          </div>

          {takedowns.length > 0 && (
            <div className="space-y-3 pt-4 border-t border-white/10">
              <h3 className="font-display font-semibold text-base text-white">
                Issued Creator Takedown Notices ({takedowns.length})
              </h3>
              <div className="space-y-2.5">
                {takedowns.map((td) => (
                  <div
                    key={td.id}
                    className="p-4 rounded-2xl bg-[#161622]/70 border border-[#EF4444]/25 space-y-2"
                  >
                    <div className="flex flex-wrap items-center justify-between gap-2">
                      <span className="font-display font-semibold text-xs sm:text-sm text-white">
                        &ldquo;{td.trackTitle}&rdquo; · Owner: {td.creatorName}
                      </span>
                      <span className="text-[10px] font-mono-tech px-2 py-0.5 rounded bg-[#EF4444]/15 text-[#fca5a5] border border-[#EF4444]/30">
                        {td.autoGenerated ? 'Auto-Generated Reason' : 'Admin Provided Reason'}
                      </span>
                    </div>
                    <p className="text-xs text-[#cbc3d7] leading-relaxed">{td.reason}</p>
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      )}

      {/* Admin Take Down Song Modal (Asks Admin for Reason or Auto-Generates) */}
      {takedownTarget && (
        <div
          onClick={(e) => {
            if (e.target === e.currentTarget && !isTakingDown) setTakedownTarget(null);
          }}
          className="fixed inset-0 z-50 bg-black/80 backdrop-blur-md flex items-center justify-center p-4"
        >
          <form
            onSubmit={(e) => void handleConfirmTakedown(e)}
            className="w-full max-w-lg rounded-3xl bg-[#0F0F16] border border-[#EF4444]/40 p-6 space-y-5 shadow-2xl"
          >
            <div className="flex items-start justify-between gap-3 pb-3 border-b border-white/10">
              <div className="space-y-1">
                <div className="inline-flex items-center gap-1.5 text-[11px] font-mono-tech text-[#EF4444] uppercase">
                  <ShieldAlert className="w-3.5 h-3.5" />
                  <span>Song Takedown &amp; Creator Notice</span>
                </div>
                <h3 className="font-display font-bold text-lg text-white">
                  Take Down &ldquo;{takedownTarget.title}&rdquo;
                </h3>
                <p className="text-xs text-[#958ea0]">
                  Creator: <strong className="text-white">{takedownTarget.creator}</strong> ({takedownTarget.creatorHandle})
                </p>
              </div>
              <button
                type="button"
                disabled={isTakingDown}
                onClick={() => setTakedownTarget(null)}
                className="p-1.5 rounded-xl text-[#958ea0] hover:text-white hover:bg-white/5"
                aria-label="Close takedown dialog"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            <div className="space-y-2.5">
              <label
                htmlFor="admin-takedown-reason"
                className="text-xs font-mono-tech text-white block"
              >
                Reason for Takedown (sent to the creator)
              </label>
              <div className="flex flex-wrap gap-1.5">
                {[
                  'Copyright / Licensing Verification Required',
                  'Incomplete or Misleading Track Metadata',
                  'Duplicate Catalog Submission',
                  'Audio File Corruption or Policy Violation',
                ].map((preset) => (
                  <button
                    key={preset}
                    type="button"
                    onClick={() => setTakedownReason(preset)}
                    className="px-2.5 py-1 rounded-lg bg-white/5 hover:bg-white/10 border border-white/10 text-[11px] font-mono-tech text-[#cbc3d7] transition-colors"
                  >
                    {preset}
                  </button>
                ))}
              </div>
              <textarea
                id="admin-takedown-reason"
                value={takedownReason}
                onChange={(e) => setTakedownReason(e.target.value)}
                rows={4}
                maxLength={900}
                placeholder="Type your reason here to notify the creator — or leave this blank and AI Music Haven will automatically generate a formal takedown reason for you..."
                className="w-full bg-[#08080C] text-xs text-white p-3 rounded-xl border border-white/10 focus:border-[#EF4444]/60 focus:outline-none"
              />
              <p className="text-[11px] text-[#958ea0]">
                {takedownReason.trim()
                  ? 'Your custom reason will be saved and sent directly to the creator.'
                  : 'No reason entered yet — submitting now will automatically generate a clear, policy-based notice for the creator.'}
              </p>
            </div>

            <div className="flex items-center justify-end gap-2.5 pt-2 border-t border-white/10">
              <button
                type="button"
                disabled={isTakingDown}
                onClick={() => setTakedownTarget(null)}
                className="px-4 py-2 rounded-xl bg-white/5 hover:bg-white/10 text-xs font-mono-tech text-[#958ea0] hover:text-white"
              >
                Cancel
              </button>
              <button
                type="submit"
                disabled={isTakingDown}
                className="inline-flex items-center gap-1.5 px-5 py-2 rounded-xl bg-[#EF4444] hover:bg-[#dc2626] text-white text-xs font-semibold shadow-lg transition-all disabled:opacity-60"
              >
                <Trash2 className="w-3.5 h-3.5" />
                <span>
                  {isTakingDown
                    ? takedownReason.trim()
                      ? 'Removing Song...'
                      : 'Auto-Generating Reason & Removing...'
                    : takedownReason.trim()
                    ? 'Take Down with Reason'
                    : 'Auto-Generate Reason & Take Down'}
                </span>
              </button>
            </div>
          </form>
        </div>
      )}
    </div>
  );
};
